    k = koordinat_getir(iata_kodu)
    if not k:
        return None
    lon1 = k["lon"] - zoom * 2
    lat1 = k["lat"] - zoom
    lon2 = k["lon"] + zoom * 2
    lat2 = k["lat"] + zoom
    return (
        f"https://www.openstreetmap.org/export/embed.html"
        f"?bbox={lon1},{lat1},{lon2},{lat2}&layer=mapnik"
        f"&marker={k['lat']},{k['lon']}"
    )
